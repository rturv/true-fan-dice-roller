#!/usr/bin/env node
/*
 * Generates the runtime environment file (`assets/env.js`) for static hosting
 * (Render, GitHub Pages, etc.), where there is no container entrypoint running
 * `envsubst` like in Docker.
 *
 * Usage:
 *   BACKEND_WS_URL=wss://api.example.com/ws/room \
 *   BACKEND_HTTP_URL=https://api.example.com \
 *   node scripts/generate-env.mjs
 *
 * Must run AFTER `ng build`: the build regenerates `dist/` from scratch.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

// Keep in sync with `projects.frontend` in angular.json.
const OUTPUT_FILE = resolve(process.cwd(), 'dist/frontend/browser/assets/env.js');

const wsUrl = (process.env.BACKEND_WS_URL ?? '').trim();
const httpUrl = (process.env.BACKEND_HTTP_URL ?? '').trim();

const warnings = [];

if (!wsUrl) {
  warnings.push(
    'BACKEND_WS_URL is empty: the app will fall back to window.location, which only ' +
      'works when the backend is served from the same origin.',
  );
} else if (!/^wss?:\/\//i.test(wsUrl)) {
  warnings.push(`BACKEND_WS_URL="${wsUrl}" does not start with ws:// or wss://.`);
} else if (wsUrl.startsWith('ws://')) {
  warnings.push(
    'BACKEND_WS_URL uses ws://: browsers block it on HTTPS pages. Use wss:// in production.',
  );
}

if (!httpUrl) {
  warnings.push(
    'BACKEND_HTTP_URL is empty: the health check URL will be derived from the WebSocket URL.',
  );
} else if (!/^https?:\/\//i.test(httpUrl)) {
  warnings.push(`BACKEND_HTTP_URL="${httpUrl}" does not start with http:// or https://.`);
}

/** Escapes a value so it is safe inside a single-quoted JS string. */
const jsString = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const content = `/*
 * Runtime environment variables.
 * Generated by scripts/generate-env.mjs at build time. Do not edit by hand.
 */
(function (window) {
  window.__env = window.__env || {};

  // Backend WebSocket URL (e.g. wss://api.example.com/ws/room)
  // Leave empty to auto-detect from window.location
  window.__env.backendWsUrl = ${jsString(wsUrl)};

  // Backend HTTP URL for REST calls (e.g. https://api.example.com)
  window.__env.backendHttpUrl = ${jsString(httpUrl)};
})(this);
`;

mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
writeFileSync(OUTPUT_FILE, content, 'utf8');

console.log(`[generate-env] Wrote ${OUTPUT_FILE}`);
console.log(`[generate-env] backendWsUrl   = ${wsUrl || '(empty)'}`);
console.log(`[generate-env] backendHttpUrl = ${httpUrl || '(empty)'}`);

for (const warning of warnings) {
  console.warn(`[generate-env] WARN: ${warning}`);
}
